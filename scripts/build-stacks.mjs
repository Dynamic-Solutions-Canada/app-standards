#!/usr/bin/env node
/**
 * Builds the per-stack indexes in `stacks/` from the rules in `standards/`.
 *
 * Each rule in a topic file has an "Applies to" line. A rule is listed in a
 * stack's index when that line names the stack, or applies to everything
 * ("all", "every", "any"). The indexes are generated so they cannot drift from
 * the rules they point at.
 *
 * Usage:
 *   node scripts/build-stacks.mjs           write stacks/*.md
 *   node scripts/build-stacks.mjs --check   exit 1 if stacks/*.md are out of date
 */

import { readFile, readdir, writeFile, mkdir } from 'node:fs/promises'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const repoRoot = join(dirname(fileURLToPath(import.meta.url)), '..')
const standardsDir = join(repoRoot, 'standards')
const stacksDir = join(repoRoot, 'stacks')

/** The stacks that get an index, with the heading and description used in each file. */
const STACKS = [
  { key: 'Windows', file: 'windows.md', title: 'Windows apps', blurb: 'WinUI tray and desktop apps, including Windows desktop hosts inside web monorepos.' },
  { key: 'Web', file: 'web.md', title: 'Web apps', blurb: 'Node and TypeScript monorepos.' },
  { key: 'Android', file: 'android.md', title: 'Android apps', blurb: 'Native Android apps and Android shells of web products.' },
  { key: 'HA', file: 'home-assistant.md', title: 'Home Assistant integration', blurb: 'Home Assistant integrations, including ones generated from a parent repo.' },
  { key: 'Kit', file: 'kits.md', title: 'Shared kits', blurb: 'Shared projects consumed by apps: winui-app-kit, apps-promo, devkit.' },
]

/** A leading word in an "Applies to" line that means the rule covers every stack. */
const UNIVERSAL = /^(all|every)\b/i

/**
 * Parses one topic file into its rules.
 *
 * @param {string} text Markdown content of a `standards/<topic>.md` file.
 * @returns {{ title: string, rules: { id: string, name: string, status: string, appliesTo: string }[] }}
 *   The file's H1 title and its rules in file order. Rules missing a field get an empty string.
 */
function parseTopic(text) {
  const title = (text.match(/^# (.+)$/m) ?? [, 'Untitled'])[1].trim()
  const rules = []
  let current = null

  for (const line of text.split('\n')) {
    const heading = line.match(/^### ([A-Z]+-\d+): (.+)$/)
    if (heading) {
      current = { id: heading[1], name: heading[2].trim(), status: '', appliesTo: '' }
      rules.push(current)
      continue
    }

    if (!current) {
      continue
    }

    const field = line.match(/^- \*\*(Status|Applies to):\*\* (.+)$/)
    if (field && field[1] === 'Status') {
      current.status = field[2].trim()
    } else if (field) {
      current.appliesTo = field[2].trim()
    }
  }

  return { title, rules }
}

/**
 * Decides whether a rule belongs in a stack's index.
 *
 * @param {string} appliesTo The rule's "Applies to" text.
 * @param {string} stackKey  One of the STACKS keys.
 */
function appliesToStack(appliesTo, stackKey) {
  // Only the primary clause decides membership. Text after ";" or "(" qualifies the rule
  // ("Android has no file to bump", "optional for Android and Kit") and must not add stacks.
  const primary = appliesTo.split(/[;(]/)[0].trim()

  if (UNIVERSAL.test(primary)) {
    return true
  }
  return new RegExp(`\\b${stackKey}\\b`).test(primary)
}

/**
 * Shortens a status line to its leading label for the index table,
 * for example "Pending D-034. Existing (5 of 11 ...)" becomes "Pending D-034".
 */
function shortStatus(status) {
  const first = status.split(/\.\s/)[0]
  const label = first.replace(/\s*\(.*$/, '').trim() || 'Unknown'

  // A pending rule can wait on several decisions; list every ID in the status, not just the first.
  if (label.startsWith('Pending')) {
    const ids = [...new Set(status.match(/D-\d{3}/g) ?? [])]
    return ids.length > 0 ? `Pending ${ids.join(', ')}` : label
  }
  return label
}

/** Renders one stack's index as Markdown. */
function renderStack(stack, topics) {
  const lines = [
    `# ${stack.title}`,
    '',
    `${stack.blurb} The rules below apply to this stack. Generated by \`scripts/build-stacks.mjs\` from \`standards/\`; do not edit by hand.`,
    '',
  ]

  for (const topic of topics) {
    // Retired rules keep their IDs in the topic file but are not part of any stack's working set.
    const rules = topic.rules.filter((rule) => {
      const retired = rule.status.startsWith('Retired')
      return !retired && appliesToStack(rule.appliesTo, stack.key)
    })
    if (rules.length === 0) {
      continue
    }

    lines.push(`## [${topic.title}](../standards/${topic.file})`, '', '| Rule | Status |', '| --- | --- |')
    for (const rule of rules) {
      lines.push(`| ${rule.id}: ${rule.name} | ${shortStatus(rule.status)} |`)
    }
    lines.push('')
  }

  return lines.join('\n')
}

/** Reads and parses every topic file, sorted by file name. */
async function loadTopics() {
  const files = (await readdir(standardsDir)).filter((name) => name.endsWith('.md')).sort()
  const topics = []
  for (const file of files) {
    const parsed = parseTopic(await readFile(join(standardsDir, file), 'utf8'))
    topics.push({ file, ...parsed })
  }
  return topics
}

/**
 * Writes each stack index, or in check mode reports which ones differ.
 *
 * @returns {Promise<number>} Process exit code: 0 when written or up to date, 1 when a check fails.
 */
async function main() {
  const checkOnly = process.argv.includes('--check')
  const topics = await loadTopics()
  await mkdir(stacksDir, { recursive: true })

  const stale = []
  for (const stack of STACKS) {
    const path = join(stacksDir, stack.file)
    const next = renderStack(stack, topics)

    if (!checkOnly) {
      await writeFile(path, next)
      continue
    }

    const existing = await readFile(path, 'utf8').catch(() => '')
    if (existing !== next) {
      stale.push(stack.file)
    }
  }

  if (stale.length > 0) {
    console.error(`Out of date: ${stale.join(', ')}. Run node scripts/build-stacks.mjs`)
    return 1
  }
  return 0
}

process.exitCode = await main()
